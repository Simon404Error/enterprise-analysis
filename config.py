# -*- coding: utf-8 -*-
"""
全局配置：路径、文件命名规则、字段名、指标定义。
修改本文件即可调整数据目录、表头字段、指标口径，无需改动其他模块。
本项目按「地区」维度的整体分析（不按单个企业）。
"""
import os
import re

# ---------------- 路径 ----------------
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(BASE_DIR, 'data')                # Excel 数据目录（可含年份子文件夹）
OUTPUT_XLSX = os.path.join(BASE_DIR, '分析结果汇总.xlsx')  # 静态输出 Excel

# ---------------- 文件名规则 ----------------
# 年度报告记录 (地区名).xlsx / .xls  或 年度报告记录 (地区名1).xlsx（数字为分卷号）
# 兼容中英文括号、可选空格；支持 .xlsx 与 .xls
FILE_PATTERN = re.compile(r'^年度报告记录\s*[（(]\s*(.+?)(\d{0,3})\s*[）)]\.xls[x]?$')
# 年份文件夹名（data/2025、data/2026 等）
YEAR_FOLDER_PATTERN = re.compile(r'^(?:19|20)\d{2}$')

# ---------------- 表头字段 ----------------
COL_ENTERPRISE = '企业名称'   # 可存在于明细中（公示按记录行判定），不强依赖
COL_YEAR = '年度'
COL_REGION = '地区'          # 由文件名解析后自动加入
COL_FILE = '来源文件'        # 记录来自哪个文件（调试用）
COL_SRC_YEAR = '来源年份'    # 来自 data/ 下的年份子文件夹名（找不到时为 NaN）

# 数值字段：按 (地区, 年度) 加总合并
NUMERIC_COLS = ['资产总额', '所有者权益合计', '销售额或营业收入',
                '利润总额', '营业总收入中主营业务收入', '净利润', '负债总额',
                '纳税总额', '资产认缴额', '资产实缴额']
# 文本业务字段（“是否”类）：不参与数值加总；公示判定中非空即视为已公示
TEXT_COLS = ['是否股权转让', '是否对外投资']

# 公示状况判定用 12 项（用户指定）
PUBLISH_COLS = TEXT_COLS + NUMERIC_COLS   # 12 项
PUBLISH_COL = '公示状况'
PUBLISH_ALL = '全部公示'
PUBLISH_PART = '部分公示'
PUBLISH_NONE = '全部不公示'

# ---------------- 派生指标 ----------------
# 比率类指标（小数，展示/导出 ×100 标 %，按地区×年度计算）
RATIO_COLS = [
    '销售净利率',              # 净利润 / 销售额
    '净利润率',                # 净利润 / 营业收入（同口径）
    '净资产收益率(ROE)',       # 净利润 / 所有者权益合计
    '资产负债率',              # 负债总额 / 资产总额
    '主营业务收入占比',        # 主营业务收入 / 营业收入
    '总资产周转率',            # 营业收入 / 平均资产总额（平均资产=(上年+当年)/2，无上年用当年）
]
# 增长率类指标（年度数据下 同比=环比；严格相邻年度，缺失/上年为0 记 NA）
GROWTH_COLS = [
    '销售额同比增长率', '销售额环比增长率',
    '净利润同比增长率', '净利润环比增长率',
    '资产总额同比增长率', '资产总额环比增长率',
    '主营业务收入同比增长率', '主营业务收入环比增长率',
]
STD_COLS = ['销售额标准差', '净利润标准差']   # 地区各年度数值的波动（万元）

# Excel 中展示为百分数的列（×100 输出）
PERCENT_COLS = RATIO_COLS + GROWTH_COLS

# 主营业务收入占比警示阈值（低于该值提示依赖非主营）
MAIN_INCOME_WARN = 0.5
# 亏损但周转快判定阈值（净利率<0 且总资产周转率高于该值，提示运营活跃、产能利用率高）
TURNOVER_ACTIVE = 1.0