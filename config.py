# -*- coding: utf-8 -*-
"""
全局配置：路径、文件命名规则、字段名、指标定义。
修改本文件即可调整数据目录、表头字段、指标口径，无需改动其他模块。
"""
import os
import re

# ---------------- 路径 ----------------
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(BASE_DIR, 'data')                # Excel 数据目录
OUTPUT_XLSX = os.path.join(BASE_DIR, '分析结果汇总.xlsx')  # 静态输出 Excel

# ---------------- 文件名规则 ----------------
# 年度报告记录（地区名）.xlsx 或 年度报告记录（地区名1）.xlsx（数字为分卷号）
# 兼容中英文括号；地区名后的数字视为分卷号
FILE_PATTERN = re.compile(r'^年度报告记录[（(](.+?)(\d*)[）)]\.xlsx$')

# ---------------- 表头字段（固定，见需求） ----------------
COL_ENTERPRISE = '企业名称'
COL_YEAR = '年度'
COL_REGION = '地区'      # 由文件名解析后自动加入
COL_FILE = '来源文件'    # 记录数据来自哪个文件（调试用）

# 数值字段：同一企业同一年度出现多条记录时，按这些字段加总合并
NUMERIC_COLS = ['资产总额', '所有者权益合计', '销售额或营业收入',
                '利润总额', '营业总收入中主营业务收入', '净利润', '负债总额']

# ---------------- 派生指标 ----------------
# 比率/增长率类指标（计算为小数，展示与导出时 ×100 并标注 %）
RATIO_COLS = [
    '销售净利率',              # 净利润 / 销售额（按企业+年度汇总口径）
    '净利润率',                # 净利润 / 营业收入（同销售净利率口径）
    '净资产收益率(ROE)',       # 净利润 / 所有者权益合计
    '资产负债率',              # 负债总额 / 资产总额（补充指标）
    '总资产周转率',            # 销售额 / 资产总额（补充指标）
    '主营业务占比',            # 主营业务收入 / 销售额（补充指标）
]
GROWTH_COLS = [
    '销售额同比增长率', '销售额环比增长率',   # 年度数据下 同比=环比
    '净利润同比增长率', '净利润环比增长率',
]
STD_COLS = ['销售额标准差', '净利润标准差']   # 按企业各年度数值的标准差（单位：万元）

# Excel 中展示为百分数的列（×100 输出）
PERCENT_COLS = RATIO_COLS + GROWTH_COLS
